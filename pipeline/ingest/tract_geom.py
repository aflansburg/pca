"""Load committed DE tract geometry -> ref_tract_geom (tract_fips -> GeoJSON), for the choropleth.

No DuckDB spatial here; generated by pipeline.reference_gen.tract_geometry.
Run: uv run python -m pipeline.ingest.tract_geom
"""

from __future__ import annotations

from pipeline.ingest._duckdb import connect, create_table, scalar
from pipeline.sources import ROOT

GEOM_PATH = ROOT / "data/reference/de_tract_geom_2020.json"

INPUTS: tuple[str, ...] = ()
OUTPUT = "ref_tract_geom"
OUTPUT_COLUMNS = {
    "tract_fips": "VARCHAR",
    "geometry_json": "VARCHAR",
}
REBUILD_IN_TEST = True  # reads the committed geometry reference file


def build(con) -> None:
    create_table(
        con,
        OUTPUT,
        "SELECT tract_fips, geometry_json "
        "FROM read_json(?, format='array', columns={'tract_fips': 'VARCHAR', 'geometry_json': 'VARCHAR'})",
        [str(GEOM_PATH)],
    )


def main() -> None:
    con = connect()
    build(con)
    n = scalar(con, "SELECT count(*) FROM ref_tract_geom")
    print(f"ref_tract_geom: {n} tracts")
    con.close()


if __name__ == "__main__":
    main()
